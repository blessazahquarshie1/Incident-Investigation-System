-- Same string format as JavaScript's Date.toISOString(): 2026-09-14T08:31:00.000Z
CREATE FUNCTION iso(ts timestamptz) RETURNS text
LANGUAGE sql IMMUTABLE AS $$
  SELECT to_char(ts AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
$$;